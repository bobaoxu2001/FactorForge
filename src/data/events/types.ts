import type { ExposureProfile, ImpactGraph } from "@/lib/events/impact";
import type { ThesisRecord } from "@/lib/events/thesis";
import type { Claim, EventRecord, SourceRecord } from "@/lib/events/types";

/** A market window the engine measures: abnormal returns around one event's time. */
export interface MarketWindowSpec {
  id: string;
  eventId: string;
  label: string;
  /** Instruments to measure; benchmarks come from instruments.json. */
  symbols: string[];
}

/** A market measurement a thesis trigger can test. */
export interface ObservationSpec {
  id: string;
  label: string;
  windowId: string;
  symbol: string;
  window: string;
  measure: "abnormal" | "raw";
}

export interface ScenarioCaseSpec {
  case: "base" | "bull" | "bear";
  title: string;
  narrative: string;
  assumptions: string[];
  catalysts: Array<{ when: string; what: string }>;
  risks: string[];
  invalidation: string[];
  indicators: string[];
  /** Instruments whose measured ranges are shown next to this case. */
  instruments: string[];
}

export interface WatchGroup {
  id: string;
  label: string;
  symbols: string[];
  why: string;
}

/** A forecast the ledger should hold for this case (generated by `npm run events:forecast`). */
export interface ForecastPlan {
  /** A date (YYYY-MM-DD), or "latest" for a rolling plan the weekly refresh re-runs on each instrument's last complete bar. */
  informationCutoff: string;
  instruments: string[];
  horizons: Array<1 | 5 | 20 | 60>;
  thesisId?: string;
}

export interface MemoParagraph {
  heading: string;
  /** Analyst text; cites claims as [ID]. Interpretation, so labelled as such. */
  body: string;
}

export interface ResearchCase {
  id: string;
  slug: string;
  title: string;
  dek: string;
  /** Edition cutoff: the latest moment any source in this edition was published. */
  asOf: string;
  primaryEventId: string;
  researchQuestions: string[];
  sources: SourceRecord[];
  events: EventRecord[];
  claims: Claim[];
  windows: MarketWindowSpec[];
  observations: ObservationSpec[];
  /** Grouping for cross-sectional reactions. */
  groups: Record<string, string>;
  graph: ImpactGraph;
  /** Window whose day-0 reaction the impact map is checked against. */
  graphWindowId: string;
  exposures: ExposureProfile[];
  watchlist: WatchGroup[];
  scenarios: ScenarioCaseSpec[];
  theses: ThesisRecord[];
  forecastPlans: ForecastPlan[];
  memo: MemoParagraph[];
  limitations: string[];
}
